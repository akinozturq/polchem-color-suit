# -*- coding: utf-8 -*-
"""
Polchem Color Suit — Semantic Versioning CLI Manager (SemVer 2.0.0)
Usage:
    python bump_version.py patch               # 1.0.0 -> 1.0.1
    python bump_version.py minor               # 1.0.1 -> 1.1.0
    python bump_version.py major               # 1.1.0 -> 2.0.0
    python bump_version.py prerelease [tag]    # 1.1.0 -> 1.1.1-rc.1 (default tag: rc)
    python bump_version.py release             # 1.1.1-rc.1 -> 1.1.1 (promotes to stable)
    python bump_version.py set <version>       # Explicitly set semver string (e.g. 1.2.3)
    python bump_version.py show                # Displays current version info
"""
import os
import sys
import json
import re
from datetime import datetime

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))
VERSION_JSON_PATH = os.path.join(ROOT_DIR, "version.json")
FRONTEND_VERSION_JS = os.path.join(ROOT_DIR, "frontend", "src", "version.js")
FRONTEND_PACKAGE_JSON = os.path.join(ROOT_DIR, "frontend", "package.json")


def load_version():
    if not os.path.exists(VERSION_JSON_PATH):
        print(f"Error: {VERSION_JSON_PATH} not found.")
        sys.exit(1)
    with open(VERSION_JSON_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def save_version(data):
    with open(VERSION_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")

    # Sync with frontend version.js if exists
    if os.path.exists(FRONTEND_VERSION_JS):
        try:
            content = f"// Generated by bump_version.py on {datetime.now().isoformat()}\n"
            content += f"export const CURRENT_VERSION = '{data['version']}';\n"
            with open(FRONTEND_VERSION_JS, "w", encoding="utf-8") as f:
                f.write(content)
        except Exception as e:
            print(f"Warning: Failed to sync {FRONTEND_VERSION_JS}: {e}")

    # Sync with frontend package.json if exists
    if os.path.exists(FRONTEND_PACKAGE_JSON):
        try:
            with open(FRONTEND_PACKAGE_JSON, "r", encoding="utf-8") as f:
                pkg = json.load(f)
            pkg["version"] = data["version"].split("-")[0]
            with open(FRONTEND_PACKAGE_JSON, "w", encoding="utf-8") as f:
                json.dump(pkg, f, indent=2, ensure_ascii=False)
                f.write("\n")
        except Exception as e:
            print(f"Warning: Failed to sync {FRONTEND_PACKAGE_JSON}: {e}")


def build_semver_string(major, minor, patch, prerelease=None, build_meta=None):
    ver = f"{major}.{minor}.{patch}"
    if prerelease:
        ver += f"-{prerelease}"
    if build_meta:
        ver += f"+{build_meta}"
    return ver


def bump(action, tag="rc"):
    data = load_version()
    old_version = data.get("version", "1.0.0")
    major = int(data.get("major", 1))
    minor = int(data.get("minor", 0))
    patch = int(data.get("patch", 0))
    prerelease = data.get("prerelease")
    build_meta = datetime.now().strftime("%Y%m%d")

    if action == "show":
        print(f"Polchem Color Suit Current Version: {old_version}")
        print(json.dumps(data, indent=2))
        return

    if action == "patch":
        patch += 1
        prerelease = None
    elif action == "minor":
        minor += 1
        patch = 0
        prerelease = None
    elif action == "major":
        major += 1
        minor = 0
        patch = 0
        prerelease = None
    elif action == "prerelease":
        if prerelease and tag in prerelease:
            match = re.search(rf"{tag}\.(\d+)", prerelease)
            if match:
                num = int(match.group(1)) + 1
                prerelease = f"{tag}.{num}"
            else:
                prerelease = f"{tag}.1"
        else:
            patch += 1
            prerelease = f"{tag}.1"
    elif action == "release":
        prerelease = None
    elif action == "set":
        raw = tag  # tag argument holds the custom version string
        match = re.match(r"^(\d+)\.(\d+)\.(\d+)(?:-([a-zA-Z0-9.-]+))?(?:\+([a-zA-Z0-9.-]+))?$", raw)
        if not match:
            print(f"Error: '{raw}' is not a valid Semantic Version (MAJOR.MINOR.PATCH[-PRERELEASE]).")
            sys.exit(1)
        major = int(match.group(1))
        minor = int(match.group(2))
        patch = int(match.group(3))
        prerelease = match.group(4)
        build_meta = match.group(5) or datetime.now().strftime("%Y%m%d")
    else:
        print(f"Unknown action: '{action}'. Available: patch, minor, major, prerelease, release, set, show")
        sys.exit(1)

    new_version = build_semver_string(major, minor, patch, prerelease, None)

    data["version"] = new_version
    data["major"] = major
    data["minor"] = minor
    data["patch"] = patch
    data["prerelease"] = prerelease
    data["build_metadata"] = build_meta
    data["release_date"] = datetime.now().strftime("%Y-%m-%d")
    data["channel"] = "prerelease" if prerelease else "stable"

    save_version(data)
    print(f"[OK] Polchem Color Suit Version Bumped: {old_version} -> {new_version}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(0)
    cmd = sys.argv[1].lower()
    arg = sys.argv[2] if len(sys.argv) > 2 else "rc"
    bump(cmd, arg)
